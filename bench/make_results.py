#!/usr/bin/env python3
import glob, os, platform, re, subprocess, sys

d, osslv, cc, speedf = sys.argv[1:5]
KINDS = {"r35asm": "upstream .S assembly (provider default on Linux/BSD x86_64)", "r35intr": "compiler intrinsics (provider default elsewhere)"}
ORDER = ["portable", "sse2", "sse41", "avx2", "avx512"]
SIZES = [64, 256, 1024, 4096, 16384, 65536, 1 << 20, 64 << 20]

def label(n):
    return {1024: "1 KiB", 4096: "4 KiB", 16384: "16 KiB", 65536: "64 KiB", 1 << 20: "1 MiB", 64 << 20: "64 MiB"}.get(n, "%d B" % n)

def load(path):
    r = {}
    for ln in open(path):
        if ln.startswith("#"): continue
        v, size, ns, mbs = ln.rstrip("\n").split("\t")
        r[(v, int(size))] = (float(ns), float(mbs))
    return r

data = {}
for f in glob.glob(os.path.join(d, "*.tsv")):
    kind, be, _ = os.path.basename(f).split(".")
    data[(kind, be)] = load(f)

cpu = next((l.split(":", 1)[1].strip() for l in open("/proc/cpuinfo") if l.startswith("model name")), platform.processor())
out = []
w = out.append
w("# Benchmark results\n")
w("Generated by `bench/make_results.py` from `bench/bench.c` output. Every number below was measured in this run; nothing is estimated.\n")
w("| | |\n|---|---|")
w("| CPU | %s |" % cpu)
w("| OS | %s %s |" % (platform.system(), platform.release()))
w("| Compiler | %s |" % cc)
w("| OpenSSL (libcrypto used by the bench) | %s |" % osslv)
w("| Method | single thread pinned to one core (`taskset -c 3`), best of 7 repetitions per cell, >=0.1 s per repetition, buffers warm, EVP context pre-fetched; MB/s = 10^6 bytes/s |")
w("| Baseline | stock upstream BLAKE3 1.8.7 C library (unprefixed, `blake3_hasher_*` called directly, its own static build with the same asm/intrinsics selection and the same forced backend); OpenSSL `SHA256`/`SHA512`/`BLAKE2B-512` through the same EVP loop |")
w("")
w("Variants: `reuse-ctx` = `EVP_DigestInit_ex2`+`Update`+`Final_ex` on a reused `EVP_MD_CTX`; `EVP_Digest` = the convenience one-shot (allocates a context per call); `chunked-4k` = 4 KiB `Update` calls.\n")

verdicts = []
for kind in KINDS:
    for be in ORDER:
        r = data.get((kind, be))
        if not r: continue
        w("## %s, backend `%s`\n" % (KINDS[kind], be))
        w("Throughput MB/s, reuse-ctx (one `Update`):\n")
        w("| size | provider EVP | upstream direct | EVP / upstream | SHA-256 | SHA-512 | BLAKE2b-512 |")
        w("|---|---:|---:|---:|---:|---:|---:|")
        for s in SIZES:
            p = r.get(("blake3-evp/reuse-ctx", s)); u = r.get(("blake3-upstream-direct/reuse-ctx", s))
            if not p or not u: continue
            ratio = p[1] / u[1] * 100
            g = lambda k: "%.0f" % r[(k, s)][1] if (k, s) in r else "-"
            w("| %s | %.0f | %.0f | %.1f%% | %s | %s | %s |" % (label(s), p[1], u[1], ratio, g("SHA256/reuse-ctx"), g("SHA512/reuse-ctx"), g("BLAKE2B-512/reuse-ctx")))
            if s >= 16384:
                verdicts.append((kind, be, "one-shot", s, ratio))
        w("")
        w("4 KiB-chunked updates, MB/s:\n")
        w("| size | provider EVP | upstream direct | EVP / upstream | SHA-256 |")
        w("|---|---:|---:|---:|---:|")
        for s in SIZES:
            p = r.get(("blake3-evp/chunked-4k", s)); u = r.get(("blake3-upstream-direct/chunked-4k", s))
            if not p or not u: continue
            ratio = p[1] / u[1] * 100
            w("| %s | %.0f | %.0f | %.1f%% | %.0f |" % (label(s), p[1], u[1], ratio, r[("SHA256/chunked-4k", s)][1]))
            verdicts.append((kind, be, "chunked", s, ratio))
        w("")
        w("Per-call cost, ns (small inputs):\n")
        w("| size | provider reuse-ctx | provider `EVP_Digest` | upstream direct | SHA-256 raw libcrypto (no EVP) | SHA-256 reuse-ctx | SHA-256 `EVP_Digest` |")
        w("|---|---:|---:|---:|---:|---:|---:|")
        for s in SIZES[:4]:
            g = lambda k: "%.0f" % r[(k, s)][0] if (k, s) in r else "-"
            w("| %s | %s | %s | %s | %s | %s | %s |" % (label(s), g("blake3-evp/reuse-ctx"), g("blake3-evp/EVP_Digest"), g("blake3-upstream-direct/reuse-ctx"), g("sha256-lowlevel/reuse-ctx"), g("SHA256/reuse-ctx"), g("SHA256/EVP_Digest")))
        w("")

w("## Targets\n")
w("### >= 16 KiB within 5% of upstream C, same backend\n")
bad = [v for v in verdicts if v[4] < 95.0]
w("| kind | backend | mode | size | EVP / upstream |")
w("|---|---|---|---|---:|")
for k, be, m, s, ratio in verdicts:
    w("| %s | %s | %s | %s | %.1f%% %s |" % (KINDS[k], be, m, label(s), ratio, "" if ratio >= 95 else "**below 95%**"))
w("")
w("%d of %d cells below 95%%.\n" % (len(bad), len(verdicts)))
w("### AVX2: BLAKE3 at 64 KiB vs SHA-256 (this CPU has SHA-NI)\n")
for kind in KINDS:
    r = data.get((kind, "avx2"))
    if r:
        b, s = r[("blake3-evp/reuse-ctx", 65536)][1], r[("SHA256/reuse-ctx", 65536)][1]
        w("* %s: BLAKE3 %.0f MB/s vs SHA-256 %.0f MB/s = **%.1fx**" % (KINDS[kind], b, s, b / s))
w("")
w("### 64 B-1 KiB: per-call EVP overhead vs OpenSSL's SHA-256\n")
w("Overhead = EVP reuse-ctx time minus the raw (no-EVP) time of the same algorithm.\n")
w("| kind | backend | size | BLAKE3 overhead ns | SHA-256 overhead ns |")
w("|---|---|---|---:|---:|")
for kind in KINDS:
    for be in ORDER:
        r = data.get((kind, be))
        if not r: continue
        for s in (64, 256, 1024):
            bo = r[("blake3-evp/reuse-ctx", s)][0] - r[("blake3-upstream-direct/reuse-ctx", s)][0]
            so = r[("SHA256/reuse-ctx", s)][0] - r[("sha256-lowlevel/reuse-ctx", s)][0]
            w("| %s | %s | %s | %.0f | %.0f |" % (KINDS[kind], be, label(s), bo, so))
w("")
w("## Intrinsics vs upstream assembly (provider EVP, reuse-ctx, MB/s)\n")
w("| backend | size | intrinsics | asm | asm / intrinsics |")
w("|---|---|---:|---:|---:|")
for be in ORDER:
    a, b = data.get(("r35intr", be)), data.get(("r35asm", be))
    if not a or not b: continue
    for s in (1024, 16384, 65536, 1 << 20, 64 << 20):
        x, y = a[("blake3-evp/reuse-ctx", s)][1], b[("blake3-evp/reuse-ctx", s)][1]
        w("| %s | %s | %.0f | %.0f | %.1f%% |" % (be, label(s), x, y, y / x * 100))
w("")
if os.path.exists(speedf):
    keep = [l for l in open(speedf).read().splitlines() if re.match(r"^(type|sha|SHA|BLAKE|blake)", l)]
    w("## `openssl speed -evp` (OpenSSL %s, provider default build, auto backend, 3 s per cell, 1000s of bytes/s)\n" % osslv)
    w("```\n" + "\n".join(keep) + "\n```\n")
print("\n".join(out))
